const languageSelect = document.getElementById("language-select");
function applyLanguage(lang) {
  const t = translations[lang] || translations.en;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.classList.toggle("rtl", lang === "ar");
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const key = el.dataset.i18nHtml;
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (t[key] !== undefined) el.placeholder = t[key];
  });
  document.title = lang === "ar" ? "السيرفر 1865 | طلب الهجرة" :
    lang === "tr" ? "1865 Sunucusu | Göç Başvurusu" :
    lang === "th" ? "เซิร์ฟเวอร์ 1865 | สมัครย้ายเซิร์ฟเวอร์" :
    lang === "id" ? "Server 1865 | Pendaftaran Migrasi" :
    lang === "ko" ? "서버 1865 | 이주 신청" : "Server 1865 | Migration Application";
  languageSelect.value = lang;
  try { localStorage.setItem("server1865-language", lang); } catch (_) {}
}
