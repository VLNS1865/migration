// Paste your deployed Google Apps Script Web App URL here (must end in /exec).
const GOOGLE_SCRIPT_URL = "PASTE_YOUR_GOOGLE_APPS_SCRIPT_WEB_APP_URL_HERE";

const form = document.getElementById("application-form");
const message = document.getElementById("form-message");
const submitButton = form.querySelector('button[type="submit"]');

form.addEventListener("submit", async (event) => {
  event.preventDefault();
  message.className = "form-message";
  const data = Object.fromEntries(new FormData(form).entries());
  for (const key of ["playerName","currentServer","alliance","additionalInfo"]) data[key] = (data[key] || "").trim();
  const t = translations[languageSelect.value] || translations.en;

  if (!data.playerName || !data.currentServer || data.heroesPower === "" || data.hqLevel === "" || data.mainSquadPower === "") {
    showMessage(t.invalid, "error"); return;
  }
  if (!/^https:\/\/script\.google\.com\/macros\/s\/.+\/exec$/.test(GOOGLE_SCRIPT_URL)) {
    showMessage(languageSelect.value === "ar" ? "لم يتم ربط النموذج بخدمة Google بعد." : "Google Sheets connection has not been configured yet.", "error"); return;
  }

  submitButton.disabled = true;
  submitButton.querySelector("span").textContent = "…";
  try {
    const body = new URLSearchParams({
      playerName:data.playerName, currentServer:data.currentServer,
      heroesPower:data.heroesPower, hqLevel:data.hqLevel,
      mainSquadPower:data.mainSquadPower, alliance:data.alliance,
      additionalInfo:data.additionalInfo
    });
    // Apps Script web apps require a simple cross-origin POST from GitHub Pages.
    await fetch(GOOGLE_SCRIPT_URL, {method:"POST", mode:"no-cors", body});
    form.reset();
    showMessage(t.success, "success");
  } catch (err) {
    showMessage(t.error, "error");
  } finally {
    submitButton.disabled = false;
    submitButton.querySelector("span").textContent = t.submit;
  }
});
function showMessage(text, type) {
  message.textContent = text;
  message.className = `form-message ${type}`;
}
